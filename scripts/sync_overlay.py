"""Copy flarecrawl's canonical Wappalyzer overlay into a consumer's data dir.

flarecrawl owns the one canonical custom overlay
(src/flarecrawl/wappalyzer_data/custom_fingerprints.json). Fathom, OTDB and
PHPScan vendor byte-identical copies of it, because none of them should take a
runtime dependency on flarecrawl and PHPScan isn't Python. This script is the
only way a copy gets made or refreshed, so the copies can go stale but never
silently diverge. See docs/overlay-consolidation.md.

Writes three files into <dest>:
  custom_fingerprints.json         byte-identical copy of the canonical overlay
  LICENSE.wappalyzer_data          GPL-3.0 notice; travels with every copy of the data
  custom_fingerprints.source.json  stamp: {canonical, commit, sha256}

The stamp's sha256 is what each consumer's test suite checks its vendored copy
against: a hand edit to a consumer's copy turns that consumer's gate red.

Exit codes: 0 ok / in sync, 1 drift (--check), 2 usage or missing files,
3 the canonical file has uncommitted changes (refuses to stamp a commit that
doesn't contain it; pass --allow-dirty for a local experiment).

EXAMPLES
  uv run python scripts/sync_overlay.py X:/Roam/OTDB/otdb/clients/wappalyzer_data
  uv run python scripts/sync_overlay.py X:/Roam/Fathom/src/fathom/clients/wappalyzer_data --check
  uv run python scripts/sync_overlay.py X:/Agntik/PHPScan/app/lib/wappalyzer/data --json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "src" / "flarecrawl" / "wappalyzer_data"
OVERLAY = DATA_DIR / "custom_fingerprints.json"
LICENSE = DATA_DIR / "LICENSE.wappalyzer_data"
STAMP_NAME = "custom_fingerprints.source.json"
# Repo-relative so the stamp reads the same on every machine.
CANONICAL_REF = "github.com/0xDarkMatter/flarecrawl/src/flarecrawl/wappalyzer_data/custom_fingerprints.json"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(ROOT), *args], capture_output=True, text=True, check=True
    ).stdout.strip()


def canonical_commit() -> tuple[str, bool]:
    """Last commit that touched the overlay, and whether the file is dirty."""
    commit = _git("log", "-1", "--format=%H", "--", str(OVERLAY.relative_to(ROOT)))
    dirty = bool(_git("status", "--porcelain", "--", str(OVERLAY.relative_to(ROOT))))
    return commit, dirty


def check(dest: Path) -> dict:
    copy = dest / OVERLAY.name
    want = sha256(OVERLAY)
    have = sha256(copy) if copy.exists() else None
    stamp_path = dest / STAMP_NAME
    stamp = json.loads(stamp_path.read_text(encoding="utf-8")) if stamp_path.exists() else {}
    return {
        "dest": str(dest),
        "in_sync": have == want and stamp.get("sha256") == want
        and (dest / LICENSE.name).exists(),
        "canonical_sha256": want,
        "copy_sha256": have,
        "stamp_sha256": stamp.get("sha256"),
        "licence_present": (dest / LICENSE.name).exists(),
    }


def sync(dest: Path, allow_dirty: bool) -> dict:
    commit, dirty = canonical_commit()
    if dirty and not allow_dirty:
        print(f"refusing: {OVERLAY} has uncommitted changes; commit first "
              "(or --allow-dirty for a local experiment)", file=sys.stderr)
        sys.exit(3)
    shutil.copyfile(OVERLAY, dest / OVERLAY.name)
    shutil.copyfile(LICENSE, dest / LICENSE.name)
    stamp = {
        "_note": "Generated by flarecrawl scripts/sync_overlay.py. Do not edit "
                 "custom_fingerprints.json here; fix it in flarecrawl and re-sync.",
        "canonical": CANONICAL_REF,
        "commit": commit + ("-dirty" if dirty else ""),
        "sha256": sha256(OVERLAY),
    }
    (dest / STAMP_NAME).write_text(json.dumps(stamp, indent=2) + "\n", encoding="utf-8")
    return {"dest": str(dest), "synced": True, **stamp}


def main(argv: list[str] | None = None) -> int:
    doc = __doc__ or ""
    parser = argparse.ArgumentParser(
        description=doc.split("\n\n")[0],
        epilog=doc[doc.find("EXAMPLES"):],
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("dest", type=Path, help="consumer's wappalyzer data directory")
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    parser.add_argument("--allow-dirty", action="store_true",
                        help="stamp even if the canonical file has uncommitted changes")
    parser.add_argument("--json", action="store_true", help="print the result as JSON")
    args = parser.parse_args(argv)

    if not args.dest.is_dir():
        print(f"not a directory: {args.dest}", file=sys.stderr)
        return 2
    result = check(args.dest) if args.check else sync(args.dest, args.allow_dirty)
    if args.json:
        print(json.dumps(result, indent=2))
    elif args.check:
        print(f"{'in sync' if result['in_sync'] else 'DRIFT'}: {args.dest}")
    else:
        print(f"synced {result['sha256'][:12]} ({result['commit'][:12]}) -> {args.dest}")
    return 0 if (not args.check or result["in_sync"]) else 1


if __name__ == "__main__":
    sys.exit(main())
