def cmd_init(args):
    out = Path(args.output)
    if out.exists() and not args.force:
        print(f"meshatlas: {out} already exists (use --force to overwrite)", file=sys.stderr)
        return 1
    lines = [INIT_HEADER, "\n# ---- nodes found in your tailnet ----"]
    try:
        st = tailscale.status()
        nodes = [st["self"]] + sorted(st["peers"], key=lambda p: (not p["online"], p["id"]))
        for p in nodes:
            reg = region(p["relay"])
            where = f"near {reg[0]} (home DERP {p['relay']})" if reg else (
                f"custom DERP region '{p['relay']}' — set a location" if p["relay"] else "unknown location")
            lines += ["", f"# {p['host']} · {p['os'] or '?'} · {'online' if p['online'] else 'offline'} · {where}",
                      f"[nodes.{toml_key(p['id'])}]"]
            lines.append(f'# location = "{p["relay"] if reg else "home"}"')
            lines.append('# role = ""')
            if p["self"]:
                lines.append("# this machine is the hub: docker/systemd/CPU are read locally")
            else:
                lines.append(f'# ssh = "root@{p["ip"]}"   # enable read-only collection over SSH')
            lines.append("# notes = []")
        print(f"found {len(nodes)} nodes in tailnet {st['tailnet']}")
    except Exception as exc:  # noqa: BLE001
        lines.append(f"# (could not read tailscale status: {exc})")
        print(f"warning: could not read tailscale status: {exc}", file=sys.stderr)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} — edit it, then run: meshatlas run -c {out}")
    return 0


def toml_key(s):
    return s if all(ch.isalnum() or ch in "-_" for ch in s) else '"' + s.replace('"', '\\"') + '"'


def cmd_check(args):
    ok = True

    def line(good, label, detail=""):
        nonlocal ok
        ok = ok and good is not False
        mark = "ok  " if good else ("--  " if good is None else "FAIL")
        print(f"[{mark}] {label}" + (f": {detail}" if detail else ""))

    try:
        cfg, path = config.load(args.config)
        line(True, "config", str(path or "none (auto-discovery)"))
    except config.ConfigError as exc:
        line(False, "config", str(exc))
        return 1
    exe = tailscale.cli_path()
    line(bool(exe), "tailscale CLI", exe or "not found")
    if not exe:
        return 1
    try:
        st = tailscale.status()
        on = [p for p in st["peers"] if p["online"]]
        line(True, "tailscale status", f"this node: {st['self']['id']} · {len(st['peers'])} peers, {len(on)} online")
    except Exception as exc:  # noqa: BLE001
        line(False, "tailscale status", str(exc))
        return 1
    if on:
        res = tailscale.ping(on[0]["ip"], 1)
        line(bool(res["times"]), f"tailscale ping {on[0]['id']}",
             f"{res['times'][0]:.0f}ms via {res['derp'] or res['route']}" if res["times"] else "no reply")
    for name, tool in (("docker", "docker"), ("systemd", "systemctl")):
        line(True if shutil.which(tool) else None, f"local {name}", "found" if shutil.which(tool) else "not installed")
    for nid, ov in cfg["nodes"].items():
        if not ov.get("ssh"):
            continue
        r = subprocess.run(["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=15", ov["ssh"], "python3 -c 'print(1)'"],
                           stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True, timeout=60)
        line(r.returncode == 0, f"ssh {nid} ({ov['ssh']})", "python3 reachable" if r.returncode == 0 else r.stderr.strip()[-160:])
    data_dir = Path(args.data_dir).expanduser() if args.data_dir else default_data_dir()
    try:
        data_dir.mkdir(parents=True, exist_ok=True)
        (data_dir / ".write-test").write_text("ok")
        (data_dir / ".write-test").unlink()
        line(True, "data dir", str(data_dir))
    except OSError as exc:
        line(False, "data dir", f"{data_dir}: {exc}")
    print("all good" if ok else "some checks failed")
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(prog="meshatlas", description="A live map of your Tailscale tailnet.")
    ap.add_argument("--version", action="version", version=f"meshatlas {__version__}")
    sub = ap.add_subparsers(dest="cmd")

    def common(p, server=True):
        p.add_argument("-c", "--config", help="config file (.toml or .json); default: search ./meshatlas.toml etc.")
        p.add_argument("--data-dir", help="where history.db lives (default ~/.local/state/meshatlas, env MESHATLAS_DATA)")
        if server:
            p.add_argument("--host", help='address to listen on ("auto" = Tailscale IP)')
            p.add_argument("--port", type=int, help="port (default 8765)")
            p.add_argument("--token", help="require this token (env MESHATLAS_TOKEN)")

    common(sub.add_parser("run", help="collect and serve the map (default)"))
    d = sub.add_parser("demo", help="serve the UI with generated data (no tailnet needed)")
    d.add_argument("--host")
    d.add_argument("--port", type=int)
    i = sub.add_parser("init", help="write a starter config from your tailnet")
    i.add_argument("-o", "--output", default="meshatlas.toml")
    i.add_argument("--force", action="store_true")
    common(sub.add_parser("check", help="check tailscale, SSH targets and the data dir"), server=False)

    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] not in ("run", "demo", "init", "check", "-h", "--help", "--version"):
        argv = ["run"] + argv   # `meshatlas --port 9000` means `meshatlas run --port 9000`
    args = ap.parse_args(argv)
    return {"run": cmd_run, "demo": cmd_demo, "init": cmd_init, "check": cmd_check}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
