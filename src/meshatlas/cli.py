"""Command line: ``meshatlas [run|init|demo|check]``."""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import __version__, config, tailscale
from .derp import region


def default_data_dir():
    env = os.environ.get("MESHATLAS_DATA")
    if env:
        return Path(env).expanduser()
    base = os.environ.get("XDG_STATE_HOME") or "~/.local/state"
    return Path(base).expanduser() / "meshatlas"


def resolve_host(host):
    if host != "auto":
        return host
    try:
        ip = tailscale.status()["self"]["ip"]
        if ip and "." in ip:
            return ip
    except Exception:  # noqa: BLE001
        pass
    return "127.0.0.1"


def cmd_run(args):
    from .core import Atlas
    from .server import make_handler, serve

    try:
        cfg, path = config.load(args.config)
    except config.ConfigError as exc:
        print(f"meshatlas: {exc}", file=sys.stderr)
        return 2
    if tailscale.cli_path() is None:
        print("meshatlas: the tailscale CLI was not found. Install Tailscale, set MESHATLAS_TAILSCALE, "
              "or try `meshatlas demo`.", file=sys.stderr)
        return 2
    srv = cfg["server"]
    host = resolve_host(args.host or srv["host"])
    port = args.port or srv["port"]
    token = args.token if args.token is not None else (os.environ.get("MESHATLAS_TOKEN") or srv["token"])
    data_dir = Path(args.data_dir).expanduser() if args.data_dir else default_data_dir()
    atlas = Atlas(cfg, data_dir)
    atlas.start()
    httpd = serve(host, port, make_handler(atlas, token=token))
    shown = host if host not in ("0.0.0.0", "::") else "<this machine>"
    print(f"MeshAtlas {__version__} · http://{shown}:{port}/" + ("?token=…" if token else ""), flush=True)
    print(f"  config: {path or 'none (auto-discovery)'} · data: {data_dir}", flush=True)
    if host in ("0.0.0.0", "::") and not token:
        print("  warning: listening on all interfaces without a token", flush=True)
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


def cmd_demo(args):
    from .server import make_handler, serve

    host = args.host or "127.0.0.1"
    port = args.port or 8765
    httpd = serve(host, port, make_handler(None, demo=True))
    print(f"MeshAtlas demo (generated data, no tailnet needed) · http://{host}:{port}/", flush=True)
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


